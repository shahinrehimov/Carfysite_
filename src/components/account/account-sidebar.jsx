"use client";

import { Link } from "@/i18n/routing";
import { usePathname, useRouter } from "next/navigation";
import { useTranslations } from "next-intl";
import Image from "next/image";
import { useState } from "react";
import { api } from "@/lib/axios";
import { deleteCookie } from "cookies-next";

export default function AccountSidebar() {
  const t = useTranslations();
  const pathname = usePathname();
  const router = useRouter();
  const [isLoggingOut, setIsLoggingOut] = useState(false);

  const menuItems = [
    {
      href: "/account",
      label: t("personal_info"),
      key: "personal_info",
    },
    {
      href: "/account/profile",
      label: t("profile"),
      key: "profile",
    },
    {
      href: "/account/cars",
      label: t("my_cars"),
      key: "cars",
    },
    {
      href: "/account/orders",
      label: t("my_orders"),
      key: "orders",
    },
    {
      href: "/account/addresses",
      label: t("my_addresses"),
      key: "addresses",
    },
    {
      href: "/account/referrals",
      label: t("referrals_bonuses"),
      key: "referrals",
    },
    {
      href: "/account/settings",
      label: t("settings"),
      key: "settings",
    },
    {
      href: "/account/notifications",
      label: t("notifications"),
      key: "notifications",
    },
    {
      href: "#",
      label: t("logout"),
      key: "logout",
      isLogout: true,
    },
  ];

  const isActive = (href) => {
    if (href === "/account") {
      return pathname === href || pathname.endsWith("/account");
    }
    return pathname?.endsWith(href);
  };

  const handleLogout = async () => {
    if (isLoggingOut) return;

    setIsLoggingOut(true);

    try {
      // Make logout API request (ignore errors - logout locally regardless)
      await api.post("/logout");
    } catch (error) {
      setIsLoggingOut(false);
      console.error("Logout error:", error);
      // Continue with logout even if API call fails
    } finally {
      console.log("Logging out");
      // Always remove authentication cookies and redirect, regardless of API response
      deleteCookie("access_token", { path: "/" });
      deleteCookie("auth_token", { path: "/" });
      deleteCookie("user_data", { path: "/" });
      // Note: Guest identifier will be automatically regenerated by GuestProvider

      // Redirect to home page
      router.push("/");
    }
  };

  return (
    <div className="bg-white  border-r border-gray-200 overflow-hidden">
      <nav className="p-2">
        {menuItems.map((item) => {
          const active = isActive(item.href);

          if (item.isLogout) {
            return (
              <button
                key={item.key}
                onClick={handleLogout}
                disabled={isLoggingOut}
                className="flex items-center  px-4 py-3 group disabled:opacity-50 disabled:cursor-not-allowed"
              >
                <span className="text-lg font-light text-gray-700 group-hover:text-danger cursor-pointer">
                  {isLoggingOut
                    ? t("logging_out") || "Logging out..."
                    : item.label}
                </span>
              </button>
            );
          }

          return (
            <Link
              key={item.key}
              href={item.href}
              className={`flex items-center gap-3 px-4 py-3 rounded-xl transition-colors text-lg   ${
                active
                  ? "text-[#00569C] font-semibold "
                  : "text-gray-700 hover:bg-gray-50 font-light"
              }`}
            >
              {item.label}
            </Link>
          );
        })}
      </nav>
    </div>
  );
}
